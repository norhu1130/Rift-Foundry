"""Static manifest connecting every locked champion to a dedicated Cog module."""

from __future__ import annotations

from dataclasses import dataclass
from importlib import import_module

from lol_build.cogs.base import ChampionCog, CogMaturity


@dataclass(frozen=True)
class ChampionCogSpec:
    """Describe the dedicated Python extension point for one champion."""

    champion_key: str
    module_name: str
    class_name: str
    maturity: CogMaturity
    blocker: str | None

    def load_class(self) -> type[ChampionCog]:
        """Import and validate the Cog class declared by this manifest entry.

        :return: Dedicated champion Cog class owned by ``module_name``.
        :raises TypeError: If the declared object is not a ChampionCog subclass.
        """
        module = import_module(self.module_name)
        candidate = getattr(module, self.class_name)
        if not isinstance(candidate, type) or not issubclass(candidate, ChampionCog):
            raise TypeError(
                f"manifest target is not a ChampionCog subclass: "
                f"{self.module_name}.{self.class_name}"
            )
        return candidate


